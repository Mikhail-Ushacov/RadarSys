def load_external_ci_json() -> List[Dict[str, Any]]:
    """
    Перевіряє наявність локального файлу `ci.json` у корені бекенду або у папці data/.
    Якщо знайдено — зчитує та конвертує об'єкти критичної інфраструктури.
    """
    possible_paths = [
        Path(__file__).parent / "ci.json",
        Path(__file__).parent / "data" / "ci.json",
        Path(__file__).parent.parent / "ci.json",
        Path(__file__).parent.parent / "data" / "ci.json",
    ]

    for p in possible_paths:
        if p.exists() and p.is_file():
            try:
                with open(p, "r", encoding="utf-8") as f:
                    data = json.load(f)

                items = data.get("items") or data.get("objects") or data if isinstance(data, list) else []
                valid_ci = []
                for entry in items:
                    name = entry.get("name") or entry.get("title")
                    lat = entry.get("lat") or entry.get("latitude")
                    lon = entry.get("lon") or entry.get("lng") or entry.get("longitude")
                    if not (name and lat is not None and lon is not None):
                        continue
                    valid_ci.append({
                        "name": str(name),
                        "lat": float(lat),
                        "lon": float(lon),
                        "alt": float(entry.get("alt", 0.0)),
                        "radius": float(entry.get("radius") or entry.get("detection_radius", 2000.0)),
                        "description": str(entry.get("description") or entry.get("sector") or "ОКІ з ci.json")
                    })

                if valid_ci:
                    print(f"[SEED] Успішно зчитано {len(valid_ci)} об'єктів з файлу: {p}")
                    return valid_ci
            except Exception as e:
                print(f"[SEED] Помилка парсингу {p}: {e}")

    return []


